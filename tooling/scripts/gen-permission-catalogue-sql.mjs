/**
 * One-shot generator for the 0007 permission-catalogue INSERT block.
 *
 * The catalogue gates every PHI route, so it is reference data and has to be
 * reproducible from `pnpm db:migrate` alone. It used to live only in
 * `packages/db/scripts/seed-permissions.mjs`, which no npm script or CI step
 * invoked: a freshly migrated + seeded database had an EMPTY `permissions`
 * table and every RBAC test failed.
 *
 * The generated SQL is committed into the migration, which stays an immutable
 * snapshot. Re-run only when the catalogue is deliberately versioned up:
 *   node tooling/scripts/gen-permission-catalogue-sql.mjs
 *
 * Uses the same regex parse as seed-permissions.mjs so the two cannot drift.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const contractsSrc = readFileSync(
  join(root, "packages/contracts/src/permissions.ts"),
  "utf8",
);

const catalogueStart = contractsSrc.indexOf("export const PERMISSION_CATALOGUE");
const templatesStart = contractsSrc.indexOf("export const SYSTEM_ROLE_TEMPLATES");
if (catalogueStart === -1 || templatesStart === -1) {
  throw new Error("cannot locate PERMISSION_CATALOGUE / SYSTEM_ROLE_TEMPLATES in contracts");
}
const catalogue = [
  ...contractsSrc
    .slice(catalogueStart, templatesStart)
    .matchAll(/"([a-z][a-z0-9_.]+)":\s*"([^"]*)"/g),
].map(([, code, description]) => ({ code, description }));

if (catalogue.length < 300) {
  throw new Error(`catalogue parse looks wrong: ${catalogue.length} entries`);
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const sql = `-- Permission catalogue (specification §2.3). Reference data rather than
-- tenant data: \`permissions\` is a GLOBAL table with no RLS. It is versioned
-- here so \`pnpm db:migrate\` alone yields a database whose permission checks
-- resolve - a fresh install must never have an empty catalogue.
-- Generated by tooling/scripts/gen-permission-catalogue-sql.mjs from
-- packages/contracts/src/permissions.ts. Do not hand-edit.
INSERT INTO permissions (code, description) VALUES
${catalogue.map((c) => `  (${q(c.code)}, ${q(c.description)})`).join(",\n")}
ON CONFLICT (code) DO UPDATE SET description = EXCLUDED.description;
`;

const out = join(root, "packages/db/migrations/.catalogue.sql");
writeFileSync(out, sql, "utf8");
console.log(`wrote ${catalogue.length} permission rows -> ${out}`);
